export function getRecruitIdsForFaction(faction: PlayableCampaignId, bonuses: CampaignBonuses): string[] {
  if (faction === 'TheKhaganate') {
    const inf = bonuses.infantryTier >= 2 ? 'k_immortals' : 'k_warriors';
    const arc = bonuses.archersTier >= 2 ? 'k_serpent_archers' : 'k_hunters';
    const cav =
      bonuses.cavalryTier === 3 ? 'k_ancient_raiders' : bonuses.cavalryTier === 2 ? 'k_raiders' : 'k_nomads';
    const siege = bonuses.siegeTier >= 2 ? 'k_poison_catapult' : 'k_trebuchet';
    return [inf, arc, cav, 'k_assassins', siege];
  }
  if (faction === 'TheCult') {
    const inf = bonuses.infantryTier >= 2 ? 'b_myrmidons' : 'b_rebels';
    const arc =
      bonuses.archersTier === 3 ? 'b_giantbots' : bonuses.archersTier === 2 ? 'b_gunbots' : 'b_gunsmiths';
    const cav = bonuses.cavalryTier >= 2 ? 'b_dragon_lancers' : 'b_lancers';
    const mag = bonuses.magicTier >= 2 ? 'b_wizards' : 'b_acolytes';
    return [inf, arc, cav, mag, 'b_trebuchet'];
  }
  const inf = bonuses.infantryTier === 3 ? 'w_legionaries' : bonuses.infantryTier === 2 ? 'w_swordsmen' : 'w_guards';
  const arc = bonuses.archersTier === 2 ? 'w_crossbowmen' : 'w_archers';
  const cav = bonuses.cavalryTier === 2 ? 'w_champions' : 'w_knights';
  const mag = bonuses.magicTier === 2 ? 'w_zealots' : 'w_monks';
  return [inf, arc, cav, mag, 'w_trebuchet'];
}

export function getWestariaRecruitIds(bonuses: CampaignBonuses): string[] {
  return getRecruitIdsForFaction('Westaria', bonuses);
}

export function getUnitDefForClass(
  faction: FactionId,
  unitClass: UnitClass,
  techLevel: 1 | 2 | 3,
): UnitDefinition | undefined {
  const candidates = Object.values(UNIT_DEFS).filter(
    (u) => u.faction === faction && u.unitClass === unitClass && u.id !== 'w_avatar',
  );
  return (
    candidates.find((u) => u.techLevel === techLevel) ??
    candidates.find((u) => u.techLevel === 2) ??
    candidates.find((u) => u.techLevel === 1) ??
    candidates[0]
  );
}

export function getRecruitOptionsForFaction(faction: FactionId): UnitDefinition[] {
  return Object.values(UNIT_DEFS).filter((u) => u.faction === faction && u.techLevel === 1);
}
